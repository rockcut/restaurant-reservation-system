-- ============================================================
-- 8. Single-seat swap RPC
-- ============================================================

create or replace function public.swap_reservation_seats(
  p_reservation_a_id bigint,
  p_seat_a integer,
  p_reservation_b_id bigint,
  p_seat_b integer
)
returns void
language plpgsql
security invoker
as $function$
begin
  -- A側が予約済み、B側も予約済み
  if p_reservation_a_id is not null
     and p_reservation_b_id is not null then

    update reservation_seats
    set seat = -1
    where reservation_id = p_reservation_a_id
      and seat = p_seat_a;

    update reservation_seats
    set seat = p_seat_a
    where reservation_id = p_reservation_b_id
      and seat = p_seat_b;

    update reservation_seats
    set seat = p_seat_b
    where reservation_id = p_reservation_a_id
      and seat = -1;

  -- Aだけ予約済み
  elsif p_reservation_a_id is not null then

    update reservation_seats
    set seat = p_seat_b
    where reservation_id = p_reservation_a_id
      and seat = p_seat_a;

  -- Bだけ予約済み
  elsif p_reservation_b_id is not null then

    update reservation_seats
    set seat = p_seat_a
    where reservation_id = p_reservation_b_id
      and seat = p_seat_b;

  end if;
end;
$function$;


-- ============================================================
-- 9. Two-seat block swap RPC
-- ============================================================

create or replace function public.swap_reservation_seat_blocks(
  p_seat_a1 integer,
  p_seat_a2 integer,
  p_seat_b1 integer,
  p_seat_b2 integer
)
returns void
language plpgsql
security invoker
as $function$
declare
  v_res_a1 bigint;
  v_res_a2 bigint;
  v_res_b1 bigint;
  v_res_b2 bigint;
begin
  select reservation_id
  into v_res_a1
  from reservation_seats
  where seat = p_seat_a1
  limit 1;

  select reservation_id
  into v_res_a2
  from reservation_seats
  where seat = p_seat_a2
  limit 1;

  select reservation_id
  into v_res_b1
  from reservation_seats
  where seat = p_seat_b1
  limit 1;

  select reservation_id
  into v_res_b2
  from reservation_seats
  where seat = p_seat_b2
  limit 1;

  -- 一時的に衝突しない値へ退避
  update reservation_seats
  set seat = -101
  where seat = p_seat_a1;

  update reservation_seats
  set seat = -102
  where seat = p_seat_a2;

  update reservation_seats
  set seat = p_seat_a1
  where seat = p_seat_b1;

  update reservation_seats
  set seat = p_seat_a2
  where seat = p_seat_b2;

  update reservation_seats
  set seat = p_seat_b1
  where seat = -101;

  update reservation_seats
  set seat = p_seat_b2
  where seat = -102;
end;
$function$;