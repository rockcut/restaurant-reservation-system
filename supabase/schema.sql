-- ============================================================
-- AuVingtQuatre Reservation Management System
-- Supabase Database Schema
--
-- This file documents the current production database structure.
-- Actual reservation/customer data is NOT included.
-- ============================================================


-- ============================================================
-- 1. reservations
-- ============================================================

create table public.reservations (
  id bigint generated by default as identity primary key,
  seat bigint not null,
  name text not null,
  people bigint not null,
  time time without time zone,
  course text,
  allergy text,
  plate text,
  plate_message text,
  phone text,
  note text,
  reservation_date date
);


-- ============================================================
-- 2. reservation_seats
--
-- Actual physical seat assignments are managed here.
-- reservations.seat is retained as a legacy representative seat.
-- ============================================================

create table public.reservation_seats (
  id bigint generated by default as identity primary key,
  reservation_id bigint not null
    references public.reservations(id)
    on delete cascade,
  seat bigint not null
);


-- ============================================================
-- 3. profiles
--
-- Application roles associated with Supabase Auth users.
-- ============================================================

create table public.profiles (
  user_id uuid primary key
    references auth.users(id)
    on delete cascade,

  role text not null
    check (role = any (array['editor'::text, 'viewer'::text]))
);


-- ============================================================
-- 4. Enable Row Level Security
-- ============================================================

alter table public.reservations
enable row level security;

alter table public.reservation_seats
enable row level security;

alter table public.profiles
enable row level security;


-- ============================================================
-- 5. profiles RLS policies
-- ============================================================

create policy "Users can read own profile"
on public.profiles
as permissive
for select
to authenticated
using (
  auth.uid() = user_id
);


-- ============================================================
-- 6. reservations RLS policies
-- ============================================================

create policy "Authenticated users can read reservations"
on public.reservations
as permissive
for select
to authenticated
using (
  true
);


create policy "Editors can insert reservations"
on public.reservations
as permissive
for insert
to authenticated
with check (
  exists (
    select 1
    from public.profiles
    where profiles.user_id = auth.uid()
      and profiles.role = 'editor'::text
  )
);


create policy "Editors can update reservations"
on public.reservations
as permissive
for update
to authenticated
using (
  exists (
    select 1
    from public.profiles
    where profiles.user_id = auth.uid()
      and profiles.role = 'editor'::text
  )
)
with check (
  exists (
    select 1
    from public.profiles
    where profiles.user_id = auth.uid()
      and profiles.role = 'editor'::text
  )
);


create policy "Editors can delete reservations"
on public.reservations
as permissive
for delete
to authenticated
using (
  exists (
    select 1
    from public.profiles
    where profiles.user_id = auth.uid()
      and profiles.role = 'editor'::text
  )
);


